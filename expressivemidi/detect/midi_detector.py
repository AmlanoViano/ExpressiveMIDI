"""
MIDI provenance detector.

Classes
    human        recorded from a human performance (piano, drums ...)
    programmed   step-entered / quantised (incl. fixed swing, constant or stepped velocity)
    random       programmed + independent random jitter (DAW-style "humanise")
    model        rendered by an expressive-performance model (e.g. ExpressiveMIDI itself)

What this can and cannot tell you
    It judges how the *performance data* was produced. It cannot tell whether a human
    or an AI *composed* the notes: an AI composition that was played in by a human
    looks human, and a human composition typed into a sequencer looks programmed.

Training data (built by `build_training_set`)
    human       ASAP/MAESTRO piano performances + Groove MIDI Dataset drum performances
    others      generated from the matching scores / quantised grooves, so every class
                contains the same pieces and the classifier must learn *how* notes were
                produced rather than *which* pieces they are.
"""
from __future__ import annotations

import copy
import os
import warnings
import zlib
from concurrent.futures import ProcessPoolExecutor

import joblib
import numpy as np
import pandas as pd
import pretty_midi

from .midi_features import FEATURE_NAMES, extract

CLASSES = ["human", "programmed", "random", "model"]
CLASS_INFO = {
    "human": "played by a person (live-recorded performance)",
    "programmed": "programmed / quantised (step-entered or snapped to grid)",
    "random": "programmed, then randomised (DAW-style 'humanise' jitter)",
    "model": "generated by an expressive-performance model (algorithmic humanisation)",
}


# --------------------------------------------------------------------------------------
# Synthetic variants
# --------------------------------------------------------------------------------------
def _load(path):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return pretty_midi.PrettyMIDI(path)


def _crop(pm, rng, min_len=15, max_len=75):
    end = pm.get_end_time()
    length = rng.uniform(min_len, max_len)
    if end <= length:
        return copy.deepcopy(pm)
    beats = pm.get_beats()
    cand = beats[beats < end - length]
    start = float(rng.choice(cand)) if len(cand) else 0.0
    out = copy.deepcopy(pm)
    for inst in out.instruments:
        inst.notes = [n for n in inst.notes if start <= n.start < start + length]
        inst.control_changes = [c for c in inst.control_changes if start <= c.time < start + length]
        inst.pitch_bends = []
    return out


def _snap_ticks(pm):
    """Round note times to the file's tick grid, as writing to disk would."""
    for inst in pm.instruments:
        for n in inst.notes:
            s = pm.tick_to_time(pm.time_to_tick(n.start))
            e = pm.tick_to_time(max(pm.time_to_tick(n.end), pm.time_to_tick(n.start) + 1))
            n.start, n.end = s, e
    return pm


def _quantise(pm, rng):
    """Snap a performance onto the 16th/triplet grid of its own tempo map (drum grooves)."""
    beats = pm.get_beats()
    from ..features import BeatGrid
    g = BeatGrid(beats)
    div = rng.choice([4, 4, 4, 12, 8])
    for inst in pm.instruments:
        for n in inst.notes:
            d = n.end - n.start
            b = np.round(g.to_beats([n.start])[0] * div) / div
            n.start = float(g.to_seconds([b])[0])
            n.end = n.start + (d if inst.is_drum else max(np.round(d / 0.125) * 0.125, 0.06))
    return pm


def _programmed_velocity(pm, rng):
    mode = rng.choice(["keep", "const", "bars", "accent"])
    beats = pm.get_beats()
    from ..features import BeatGrid
    g = BeatGrid(beats)
    const = int(rng.choice([64, 80, 90, 96, 100, 110, 127]))
    bar_vels = rng.choice([50, 64, 80, 96, 110], size=4096)
    for inst in pm.instruments:
        for n in inst.notes:
            if mode == "const":
                n.velocity = const
            elif mode == "bars":
                n.velocity = int(bar_vels[int(g.to_beats([n.start])[0] // 4) % 4096])
            elif mode == "accent":
                frac = g.to_beats([n.start])[0] % 1
                n.velocity = int(np.clip(const + (15 if frac < 0.02 else -10), 1, 127))
    return pm


def _swing(pm, rng):
    if rng.random() > 0.25:
        return pm
    beats = pm.get_beats()
    from ..features import BeatGrid
    g = BeatGrid(beats)
    amt = rng.uniform(0.04, 0.16)  # fraction of a beat to delay off-beat 8ths
    for inst in pm.instruments:
        for n in inst.notes:
            b = g.to_beats([n.start])[0]
            if abs((b % 1) - 0.5) < 0.02:
                d = n.end - n.start
                n.start = float(g.to_seconds([b + amt])[0])
                n.end = n.start + d
    return pm


def make_programmed(pm, rng):
    return _swing(_programmed_velocity(pm, rng), rng)


def make_random(pm, rng):
    pm = make_programmed(pm, rng)
    sigma = rng.uniform(0.002, 0.03)
    vel_range = rng.choice([0, 5, 10, 20])
    do_t = rng.random() < 0.85
    dist = rng.choice(["normal", "uniform"])
    for inst in pm.instruments:
        for n in inst.notes:
            if do_t:
                j = rng.normal(0, sigma) if dist == "normal" else rng.uniform(-sigma * 1.7, sigma * 1.7)
                d = n.end - n.start
                n.start = max(0.0, n.start + j)
                n.end = n.start + d
            if vel_range:
                n.velocity = int(np.clip(n.velocity + rng.integers(-vel_range, vel_range + 1), 1, 127))
    return pm


_MODEL = None


def make_model(pm, rng, model_path):
    global _MODEL
    from ..humanise import Settings, humanise_midi, load_model
    if _MODEL is None:
        import torch
        torch.set_num_threads(1)
        _MODEL = load_model(model_path)
    pm = _programmed_velocity(pm, rng)
    s = Settings(strength=float(rng.uniform(0.4, 1.6)), rubato=float(rng.choice([0, 0.5, 1.0])),
                 drums=float(rng.uniform(0.5, 1.5)), seed=int(rng.integers(1 << 30)), tag=False)
    out, _ = humanise_midi(pm, *_MODEL, s)
    return out


