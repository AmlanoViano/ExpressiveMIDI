_DET = {}


def load_detector(path="models/midi_detector.joblib"):
    if path not in _DET:
        _DET[path] = joblib.load(path)
    return _DET[path]


def explain(f):
    """Human-readable evidence from the raw features."""
    v = dict(zip(FEATURE_NAMES, f))
    ev = []
    ev.append(f"{v['grid_1ms']:.0%} of notes land exactly (<1 ms) on the beat grid")
    if v["chord_exact_frac"] > 0:
        ev.append(f"{v['chord_exact_frac']:.0%} of chords are perfectly simultaneous "
                  f"(avg spread {v['chord_spread_ms']:.1f} ms)")
    ev.append(f"timing-deviation autocorrelation {v['dev_ac1']:+.2f} "
              "(humans drift smoothly > 0; random jitter = 0)")
    ev.append(f"{int(round(v['vel_unique'] * 127))} distinct velocities, "
              f"{v['vel_mode_frac']:.0%} share the most common value")
    ev.append(f"{v['dur_grid_1ms']:.0%} of note lengths are exact grid values")
    return ev


def detect_midi(path, detector_path="models/midi_detector.joblib"):
    det = load_detector(detector_path)
    pm = _load(path)
    tagged = any("ExpressiveMIDI" in t.text for t in pm.text_events)
    n = sum(len(i.notes) for i in pm.instruments)
    f = extract(pm)
    probs = det["model"].predict_proba(f[None])[0]
    res = dict(file=os.path.basename(path), type="midi", notes=n,
               probabilities={c: float(p) for c, p in zip(det["classes"], probs)},
               p_human=float(probs[0]), evidence=explain(f), tagged_by_expressivemidi=tagged)
    best = det["classes"][int(np.argmax(probs))]
    res["verdict"] = best
    res["verdict_text"] = CLASS_INFO[best]
    notes = []
    if n < 60:
        notes.append("Very few notes - low confidence.")
    if max(probs) < 0.6:
        notes.append("No class is clearly dominant - treat as uncertain.")
    if tagged:
        notes.append("File carries an ExpressiveMIDI 'humanised' marker.")
    notes.append("This judges how the notes were *performed/produced*, not who composed them.")
    res["notes"] = notes
    return res
