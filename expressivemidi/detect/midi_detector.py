def _split(key):
    h = zlib.crc32(key.encode()) % 100
    return "test" if h < 8 else "validation" if h < 16 else "train"


def _sample_job(args):
    kind, path, label, split, seed, model_path, group = args
    rng = np.random.default_rng(seed)
    try:
        pm = _crop(_load(path), rng)
        if kind == "score_perf":            # human performance: as is
            pass
        elif kind == "quantise_groove":       # drum grooves need quantising first
            pm = _quantise(pm, rng)
        if label == "programmed":
            pm = make_programmed(pm, rng)
        elif label == "random":
            pm = make_random(pm, rng)
        elif label == "model":
            pm = make_model(pm, rng, model_path)
        if label != "human":
            pm = _snap_ticks(pm)
        return extract(pm), CLASSES.index(label), split, group
    except Exception as e:  # noqa: BLE001
        return None


def build_jobs(asap_dir, groove_dir, model_path, reps=3, seed=0):
    jobs = []
    rng = np.random.default_rng(seed)
    meta = pd.read_csv(os.path.join(asap_dir, "metadata.csv"))
    for _, r in meta.iterrows():
        split = _split(r["folder"])
        for k in range(reps):
            jobs.append(("score_perf", os.path.join(asap_dir, r["midi_performance"]), "human", split,
                         int(rng.integers(1 << 30)), model_path, r["folder"]))
    # one score per performance row -> classes stay balanced and piece-matched
    for _, r in meta.iterrows():
        split = _split(r["folder"])
        for label in ("programmed", "random", "model"):
            jobs.append(("score", os.path.join(asap_dir, r["midi_score"]), label, split,
                         int(rng.integers(1 << 30)), model_path, r["folder"]))
    if groove_dir:
        g = pd.read_csv(os.path.join(groove_dir, "info.csv"))
        for _, r in g.iterrows():
            split = _split(r["session"])
            p = os.path.join(groove_dir, r["midi_filename"])
            jobs.append(("groove", p, "human", split, int(rng.integers(1 << 30)), model_path, r["session"]))
            label = rng.choice(["programmed", "random", "model"])
            jobs.append(("quantise_groove", p, str(label), split, int(rng.integers(1 << 30)), model_path,
                         r["session"]))
    return jobs


def build_training_set(asap_dir, groove_dir, model_path, out_path="data/processed/midi_detector.npz",
                       workers=4, reps=3):
    jobs = build_jobs(asap_dir, groove_dir, model_path, reps)
    with ProcessPoolExecutor(workers) as ex:
        res = [r for r in ex.map(_sample_job, jobs, chunksize=16) if r is not None]
    X = np.stack([r[0] for r in res])
    y = np.array([r[1] for r in res])
    split = np.array([r[2] for r in res])
    group = np.array([r[3] for r in res])
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    np.savez_compressed(out_path, X=X, y=y, split=split, group=group)
    print(f"{len(res)}/{len(jobs)} samples, class counts {np.bincount(y)}")
    return out_path


def train(data_path="data/processed/midi_detector.npz", out_path="models/midi_detector.joblib"):
    from sklearn.ensemble import HistGradientBoostingClassifier
    from sklearn.metrics import classification_report, confusion_matrix, roc_auc_score

    d = np.load(data_path)
    X, y, split = d["X"], d["y"], d["split"]
    tr = split != "test"
    clf = HistGradientBoostingClassifier(max_iter=400, learning_rate=0.08, max_leaf_nodes=31,
                                         l2_regularization=1.0, class_weight="balanced", random_state=0)
    clf.fit(X[tr], y[tr])
    te = split == "test"
    p = clf.predict_proba(X[te])
    pred = p.argmax(1)
    report = classification_report(y[te], pred, target_names=CLASSES, digits=3)
    cm = confusion_matrix(y[te], pred)
    auc = roc_auc_score(y[te] == 0, p[:, 0])
    print(report)
    print("confusion (rows=true, cols=pred):", CLASSES)
    print(cm)
    print(f"human-vs-machine ROC AUC: {auc:.4f}")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    joblib.dump(dict(model=clf, features=FEATURE_NAMES, classes=CLASSES,
                     test_report=report, test_confusion=cm.tolist(), test_auc=auc), out_path)
    return report


